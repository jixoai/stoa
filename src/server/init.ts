import { appendFileSync, chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { randomBytes } from "node:crypto";
import { fail } from "../core/errors.ts";
import { parseEnv, resolveEnvFiles, loadEnvFiles } from "../core/env.ts";
import { maskSecret } from "../core/auth.ts";
import { assertSafeDataDir, writePointer } from "./discovery.ts";
import { openDatabase, migrate } from "./db.ts";
import { Store } from "./store.ts";

export interface InitResult {
  data_dir: string;
  database: string;
  secret_file: string;
  pointer: string;
  accounts: Array<{ id: string; role: string; env_file: string }>;
  auth: {
    mode: "open" | "auth";
    provisioned: boolean;
    provisioned_value: string | null;
    provisioned_file: string | null;
    env_files: string[];
    hint: string | null;
  };
}

function writeSecure(path: string, content: string, mode = 0o600): void {
  writeFileSync(path, content, { mode });
  chmodSync(path, mode);
}

export function initDataDir(opts: {
  dataDir: string;
  cwd?: string;
  envFiles?: string[] | null;
  now?: number;
}): InitResult {
  const cwd = opts.cwd ?? process.cwd();
  const dataDir = assertSafeDataDir(opts.dataDir, { cwd });
  const dbPath = join(dataDir, "report.sqlite");
  if (existsSync(dbPath)) {
    fail("CONFLICT", `data dir ${dataDir} is already initialized (report.sqlite exists)`);
  }
  mkdirSync(dataDir, { recursive: true, mode: 0o700 });
  mkdirSync(join(dataDir, "accounts"), { recursive: true, mode: 0o700 });
  mkdirSync(join(dataDir, "media"), { recursive: true, mode: 0o700 });
  mkdirSync(join(dataDir, "export"), { recursive: true, mode: 0o700 });

  const envPath = join(dataDir, ".env");
  let secret = "";
  if (existsSync(envPath)) {
    const existing = parseEnv(readFileSync(envPath, "utf8"));
    secret = existing.FDE2E_REPORT_SECRET ?? "";
  }
  if (!secret) {
    secret = randomBytes(32).toString("hex");
    const block = [
      "# stoa server config (generated by init; 0600)",
      `FDE2E_REPORT_SECRET=${secret}`,
      "",
    ].join("\n");
    if (existsSync(envPath)) appendFileSync(envPath, `\n${block}`);
    else writeSecure(envPath, block);
    chmodSync(envPath, 0o600);
  }

  const db = openDatabase({ dataDir });
  let accounts: InitResult["accounts"] = [];
  try {
    migrate(db);
    const store = new Store({ dataDir, db, clock: opts.now ? () => opts.now! : Date.now });
    const owner = store.ensureInitAccount({ id: "owner", role: "owner", display: "owner" });
    const manager = store.ensureInitAccount({ id: "manager", role: "manager", display: "manager" });
    // design §5.0: owner follows manager by default (the following feed must never
    // start out flooded by every agent).
    store.ensureDefaultFollows();
    accounts = [
      { id: "owner", role: "owner", env_file: owner.envPath },
      { id: "manager", role: "manager", env_file: manager.envPath },
    ];
  } finally {
    db.close();
  }

  const pointer = writePointer(cwd, dataDir);

  // First provision: if an env-file exists but has no FDE2E_REPORT_AUTH, append a
  // random value once and print it (design §4).
  const envFiles =
    opts.envFiles && opts.envFiles.length > 0
      ? opts.envFiles
      : resolveEnvFiles({ dataDir, cwd });
  const loaded = loadEnvFiles(envFiles);
  const existingAuth = loaded.values.FDE2E_REPORT_AUTH ?? "";
  let provisioned = false;
  let provisionedValue: string | null = null;
  let provisionedFile: string | null = null;
  let hint: string | null = null;
  if (existingAuth) {
    // already configured
  } else if (loaded.loaded.length > 0) {
    provisionedFile = loaded.loaded[0]!;
    provisionedValue = randomBytes(24).toString("base64url");
    const prefix = readFileSync(provisionedFile, "utf8").endsWith("\n") ? "" : "\n";
    appendFileSync(
      provisionedFile,
      `${prefix}\n# generated by stoa init (shown once)\nFDE2E_REPORT_AUTH=${provisionedValue}\n`,
    );
    provisioned = true;
  } else {
    const suggested = envFiles[0] ?? join(cwd, ".env.personal");
    hint =
      `no env-file exists yet; auth stays OFF (open mode). To enable auth later run:\n` +
      `  printf 'FDE2E_REPORT_AUTH=%s\\n' "$(openssl rand -base64 24)" >> ${suggested}`;
  }

  return {
    data_dir: dataDir,
    database: dbPath,
    secret_file: envPath,
    pointer,
    accounts,
    auth: {
      mode: existingAuth || provisioned ? "auth" : "open",
      provisioned,
      provisioned_value: provisionedValue,
      provisioned_file: provisionedFile,
      env_files: envFiles,
      hint,
    },
  };
}

export function describeAuthProvision(result: InitResult): string {
  if (result.auth.provisioned && result.auth.provisioned_value) {
    return (
      `FDE2E_REPORT_AUTH=${result.auth.provisioned_value}\n` +
      `(written once to ${result.auth.provisioned_file}; save it in your secrets manager)\n`
    );
  }
  if (result.auth.mode === "auth") {
    return "auth: enabled (existing FDE2E_REPORT_AUTH found)\n";
  }
  return result.auth.hint ? `${result.auth.hint}\n` : "auth: disabled (open mode)\n";
}

export function describeSecretFile(path: string): string {
  return `server secret: ${path} (${maskSecret("present")})`;
}
